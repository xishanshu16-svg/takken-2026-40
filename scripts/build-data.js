import fs from 'node:fs';
import {CORE_NUMBERS} from '../js/curriculum.js';
const root=new URL('../',import.meta.url);
const read=p=>JSON.parse(fs.readFileSync(new URL(p,root),'utf8'));
const write=(p,x)=>fs.writeFileSync(new URL(p,root),JSON.stringify(x,null,2)+'\n');
const qs=['brokerage','civil','regulations-tax'].flatMap(name=>read('data/'+name+'.json'));
write('data/exam-2026.json',qs.filter(q=>q.set==='exam').sort((a,b)=>a.number-b.number));
write('data/extra-questions.json',qs.filter(q=>q.set==='extra').sort((a,b)=>a.number-b.number));
const exam=qs.filter(q=>q.set==='exam');
const points=CORE_NUMBERS.map(number=>exam.find(q=>q.number===number)).map(q=>({questionId:q.id,number:q.number,theme:q.theme,field:q.field,importance:q.importance,point:q.point,law:q.law,articles:q.articles}));
points.find(p=>p.number===17).point='通常の新築では、2階建ての木造住宅は都市計画区域外でも建築確認の対象。区域外だから不要、と判断しない。';
points.find(p=>p.number===15).point='市街化区域は、すでに市街地を形成する区域と、おおむね10年以内に優先して市街化を図る区域。用途地域を定める。調整区域の用途地域は原則なし。';
points.find(p=>p.number===38).point='業者売主→非業者買主。申込場所を確認し、所定の告知日を含む8日以内に書面発送。全額支払と引渡しの両方が済むと不可。';
points.find(p=>p.number===39).point='業者売主→非業者買主。種類・品質の契約不適合の通知期間を特約で定めるなら「引渡しから2年以上」。契約日起算と混同しない。';
points.find(p=>p.number===40).point='業者売主→非業者買主。損害賠償予定額と違約金の合計は代金の20％まで。超過部分だけ無効。';
points.find(p=>p.number===41).point='業者売主→非業者買主の未完成物件。手付金等が代金5％以下かつ1,000万円以下なら原則保全不要。必要なら受領前に全額保全。';
points.find(p=>p.number===43).point='税抜800万円以下の低廉な空家等。事前説明・合意をし、媒介費用を勘案。媒介報酬の特例は1当事者につき税込33万円以内。';
write('data/study-points.json',points);
const analyses=Object.fromEntries(['brokerage','civil','regulations-tax'].map(name=>[{'brokerage':'宅建業法','civil':'権利関係','regulations-tax':'法令上の制限・税その他'}[name],read('reports/'+name+'-analysis.json')]));
write('reports/analysis.json',analyses);
await import('./create-mobile-report.js');
console.log(`公開教材: 厳選${exam.length}問、先に覚える${points.length}項目。追加問題は旧版の編集用データとして保管。`);
